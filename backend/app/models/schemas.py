from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any

class SchemeEligibility(BaseModel):
    gender: List[str] = ["All"]
    min_age: int = 0
    max_age: int = 100
    max_annual_income: Optional[float] = None
    residence_required: str = "Maharashtra Domicile"
    required_categories: List[str] = ["All"]
    farmer_only: bool = False
    disability_required: bool = False
    student_only: bool = False
    criteria_points: List[str] = []

class SchemeBase(BaseModel):
    id: str
    name_en: str
    name_mr: str
    name_hi: str
    department_id: str
    department_name: str
    category: str
    target_beneficiary: str
    financial_benefit: str
    short_description: str
    eligibility: SchemeEligibility
    required_documents: List[str]
    application_mode: str
    official_portal: str
    rts_delivery_days: int
    source_gr: str

class ServiceRequiredDoc(BaseModel):
    name: str
    options: List[str]

class ServiceBase(BaseModel):
    id: str
    name_en: str
    name_mr: str
    name_hi: str
    department_id: str
    department_name: str
    category: str
    issuing_authority: str
    statutory_rts_days: int
    first_appellate_authority: str
    second_appellate_authority: str
    government_fee: str
    validity: str
    short_description: str
    required_documents: List[ServiceRequiredDoc]
    procedure_steps: List[str]
    portal_url: str

class DepartmentInfo(BaseModel):
    id: str
    name_en: str
    name_mr: str
    name_hi: str
    icon: str
    key_services_count: int
    nodal_officer: str
    helpline: str
    website: str
    description: str

class SetuKendra(BaseModel):
    name: str
    taluka: str
    address: str
    timings: str
    contact: str

class DistrictInfo(BaseModel):
    district_id: str
    district_name_en: str
    district_name_mr: str
    division: str
    collectorate_address: str
    helpline: str
    setu_kendras: List[SetuKendra]
    major_talukas: List[str]

class EligibilityRequest(BaseModel):
    age: int = Field(..., ge=0, le=120)
    gender: str = Field(..., description="Male, Female, Other")
    annual_income: float = Field(..., ge=0)
    category: str = Field(..., description="Open, General, SC, ST, OBC, VJNT, SBC, EWS, Neo-Buddhist")
    district: str = "Pune"
    is_farmer: bool = False
    has_disability: bool = False
    is_student: bool = False
    ration_card_type: Optional[str] = "Orange"

class SchemeEligibilityMatch(BaseModel):
    scheme_id: str
    scheme_name: str
    category: str
    financial_benefit: str
    eligible: bool
    match_percentage: int
    satisfied_conditions: List[str]
    unmet_conditions: List[str]
    required_documents: List[str]
    official_portal: str
    source_gr: str

class EligibilityResponse(BaseModel):
    total_evaluated: int
    eligible_count: int
    matches: List[SchemeEligibilityMatch]
    summary_advice: str

class AssistantQuery(BaseModel):
    query: str
    language: str = "en"  # "en", "mr", "hi"
    context: Optional[Dict[str, Any]] = None

class AssistantResponse(BaseModel):
    answer: str
    language: str
    suggested_schemes: List[Dict[str, Any]] = []
    suggested_services: List[Dict[str, Any]] = []
    rts_statutory_timeline: Optional[str] = None
    source_citations: List[str] = []
    confidence_score: float = 0.95
    disclaimer: str = "This response is generated by MahaSeva AI for informational purposes. Please verify details on official Maharashtra portals."

class GrievanceSubmission(BaseModel):
    citizen_name: str
    phone_number: str
    email: Optional[str] = None
    district: str
    taluka: Optional[str] = None
    department_id: str
    category: str
    subject: str
    description: str
    address: Optional[str] = None
    preferred_language: str = "en"

class GrievanceTimelineEvent(BaseModel):
    timestamp: str
    stage: str
    status: str
    officer_remark: str
    updated_by: str

class GrievanceRecord(BaseModel):
    token_id: str
    citizen_name: str
    phone_number: str
    email: Optional[str] = None
    district: str
    taluka: Optional[str] = None
    department_id: str
    department_name: str
    category: str
    subject: str
    description: str
    priority_level: str  # Critical, High, Medium, Standard
    priority_score: int
    current_status: str  # Registered, Assigned, Under Investigation, Action In Progress, Resolved
    assigned_officer: str
    sla_target_days: int
    days_remaining: int
    created_at: str
    updated_at: str
    timeline: List[GrievanceTimelineEvent]

class GrievanceStatusResponse(BaseModel):
    found: bool
    record: Optional[GrievanceRecord] = None
    message: Optional[str] = None

class DocumentAnalysisRequest(BaseModel):
    document_type: str
    content_text: str

class DocumentAnalysisResponse(BaseModel):
    document_type: str
    is_valid_format: bool
    extracted_entities: Dict[str, Any]
    detected_missing_fields: List[str]
    checklist_status: str
    recommended_next_steps: List[str]
